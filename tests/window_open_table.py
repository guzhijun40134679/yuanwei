"""开启判表（禁读按窗口·交回点甲）：「用户这一条输入，算不算在明确允许本插件在这个窗口里使用长期记忆」。

**交回点乙的变化（主会话裁定二，11-10）：开不再靠规则认用户的话。** 开只有口令 #yuanwei-mem，和「agent 申请、用户下一条输入第一行是确认开启」两条路。
下面每一句的 verdict（开／不开／没确认）是交回点甲时的开侧判法，已作废，只留作句子来源；这张表现在有两种用途：
关侧——ban_now、ban_want、BAN_NOW_TRUE（关的规则识别，乙已按裁定一第 6 条补漏）；开侧——一条总测试：关着的窗口里，这些句子一句也打不开（tests/test_window.py）。
下面的 docstring 其余部分是甲版原文，保留作记录。

全部是自造的句子，没有用 11-08 锁在仓库外的禁读测试句（那一批留着以后真模型量可靠度用）。
设计依据：设计第 2 版第 5 节（正例、反例照抄进来，标 source="design"）。

三种判法（每一句只有一种）：
* open：正向规则认定「当前、直接、允许本插件用记忆」。其余核对（来源是用户本人、原文绑定、顺序、设置）也过时，结果是「已打开」。
* not_open：规则认定这不是许可（有明确的反向因素：否定、引用、转述、假设、将来、问句、代码或附件里的字、后面撤回、范围不对）。
* unconfirmed：规则认不了（规则外的说法、含糊、混杂、依赖上文）。
not_open 和 unconfirmed 对外是同一句回执（「还未确认重新允许；请明确说这个窗口可以使用记忆。」），区别只在内部原因码和计数；是否把两者对外分开，交回点甲问题 1。

字段：
* id：编号；cat：类别；text：用户这一条输入的全文（可含换行）；verdict：上面三种之一；reason：为什么；source：design（设计第 5 节原句）或 own（自造）。
* ban_now：现行 gate.read_ban（关的那一侧的「规则识别」）对这一句的实际返回，是测试钉住的实测值，不是期望。
* ban_want：按意思，这句话是不是在说「别用记忆」（关的那一侧本来该关）。ban_want 为真而 ban_now 为假＝关的一侧现行规则没认出来（漏关）；反过来＝多关。
  关是「宽」的方向，这两处都只做记录，这一单不改 gate.py（施工单：不改写入判断；关的规则识别不在这一单范围里）。
* note：可选，补充说明。

「引文核对表」是另一张：开启申请带的引文（授权原句）和输入原文怎么核。
"""

OPEN, NOT_OPEN, UNCONFIRMED = "open", "not_open", "unconfirmed"
VERDICTS = (OPEN, NOT_OPEN, UNCONFIRMED)

# 类别（施工单要求至少覆盖的十类，加四类自己补的）
CATEGORIES = (
    "positive",         # 正例
    "negation",         # 否定
    "quote",            # 引号里的话
    "third_party",      # 别人的建议（含助手上一条的建议）
    "hypothetical",     # 假设、条件
    "future",           # 讨论以后的事、不是现在
    "howto",            # 问开关怎么用、问现在开没开
    "code_attachment",  # 代码和附件里的字
    "retract",          # 同一条里先允许后撤回（及先关后开）
    "mixed",            # 混在一起判不清
    "outside_rules",    # 规则外但意思对的说法
    "scope",            # 范围不是这个窗口（自补）
    "write_not_read",   # 写入要求不是读取许可（自补）
    "english",          # 英文（自补）
)

_rows = []


def _r(id, cat, text, verdict, reason, ban_want=False, source="own", note=None):
    assert verdict in VERDICTS and cat in CATEGORIES
    _rows.append({"id": id, "cat": cat, "text": text, "verdict": verdict, "reason": reason, "ban_want": ban_want, "source": source, "note": note})


